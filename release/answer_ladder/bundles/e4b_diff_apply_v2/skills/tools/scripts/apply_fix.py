"""Apply the given fix exactly (diff test, arm D1): python3 .git/tools/apply_fix.py <task id>. Runs git apply on the saved patch.
Works from run_command and from run_skill_script, with or without arguments: a known task id anywhere in the arguments picks
that fix; otherwise the one saved fix that applies cleanly to this repository is used."""
import os, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from fixes_data import FIXES   # {task id: patch text}, generated by diff2_prep.py


def find_repo() -> Path:
    for c in ["/workspace", os.getcwd(), *os.environ.get("PYTHONPATH", "").split(os.pathsep), str(HERE.parents[1])]:
        if c and (Path(c) / ".git").is_dir():
            return Path(c)
    return Path(os.getcwd())


def git(repo, *args, stdin=None):
    return subprocess.run(["git", *args], input=stdin, cwd=repo, capture_output=True, text=True)


repo = find_repo()
words = " ".join(sys.argv[1:]).replace("=", " ").replace(",", " ").replace('"', " ").replace("'", " ").split()
key = next((w for w in words if w in FIXES), None)
if key is None:
    fits = [k for k, p in FIXES.items() if git(repo, "apply", "--check", "-", stdin=p).returncode == 0]
    key = fits[0] if len(fits) == 1 else None
    if key is None:
        sys.exit("FIX NOT APPLIED: give the task id, e.g. python3 .git/tools/apply_fix.py fastapi_11355"
                 + (" (the fix may already be applied)" if not fits else ""))
r = git(repo, "apply", "--whitespace=nowarn", "-", stdin=FIXES[key])
if r.returncode:
    sys.exit("FIX NOT APPLIED: git apply failed (already applied, or files changed since): " + (r.stderr or r.stdout)[-400:])
print("FIX APPLIED.\n" + git(repo, "diff", "--stat").stdout + "\nNext: call submit_patch.")
